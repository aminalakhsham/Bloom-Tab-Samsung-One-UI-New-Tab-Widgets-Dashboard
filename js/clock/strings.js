// forms picked with pl() from zones.js (Arabic has all six).
import { addStrings } from '../core/i18n.js';

const forms = (one, other, o = {}) => ({ zero: o.zero ?? other, one, two: o.two ?? other, few: o.few ?? other, many: o.many ?? other, other });
const plural = (prefix, f) => Object.fromEntries(Object.entries(f).map(([k, v]) => [`${prefix}.${k}`, v]));

