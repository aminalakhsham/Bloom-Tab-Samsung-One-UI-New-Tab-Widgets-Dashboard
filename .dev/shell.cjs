  ok(((await pget('edge')) || []).filter((x) => x.url === 'https://www.wikipedia.org/').length === 1 && (await page.evaluate(() => document.querySelector('.ou-toast')?.textContent)) === (await S('edge.already')), 'Apps screen: adding it twice says "Already in the Edge panel"');
  await page.evaluate((v) => { const i = document.querySelector('.drawer-input'); i.value = v; i.dispatchEvent(new Event('input')); }, calcName);
  await sleep(250);
  const homeBefore = JSON.stringify(await pget('home'));
  const ct = await rect('#drawer .tile');
  await page.mouse.click(ct.x + ct.w / 2, ct.y + ct.h / 2, { button: 'right' });
  await sleep(300);
  ok((await count('.ou-menu .ou-menu-item')) === 2, 'Apps screen: app context menu (Add to Home, Add to Edge)');
  await page.$$eval('.ou-menu .ou-menu-item', (l) => l[0].click());
  await sleep(400);
  const home1 = await pget('home');
  ok(JSON.stringify(home1) !== homeBefore && home1.flat().some((x) => x.type === 'app' && x.app === 'calculator'), 'Apps screen: Add to Home puts Calculator on the Home screen');
  await press('Escape', 200);
  await press('Escape', 400);
  ok(!(await drawerOpen()), 'Apps screen: Escape closes');
  noErrors(mark, 'Apps screen');

  // ════════════════════════════════════════ keyboard shortcuts
  mark = logs.length;
  await mod('./js/shell/edge.js', 'closeEdge');
  await page.evaluate(() => document.activeElement?.blur());
  await combo(['Alt'], 'q');
  ok(await qpOpen(), 'Alt+Q opens the Quick Panel');
  await combo(['Alt'], 'q');
  ok(!(await qpOpen()), 'Alt+Q closes it');
  await combo(['Alt'], 'a', 600);
  ok(await drawerOpen(), 'Alt+A opens the Apps screen');
  await combo(['Alt'], 'a');
  ok(!(await drawerOpen()), 'Alt+A closes it');
  await combo(['Alt'], 'e');
  ok(await edgeOpen(), 'Alt+E opens the Edge panel');
  await combo(['Alt'], 'e');
  ok(!(await edgeOpen()), 'Alt+E closes it');
  await combo(['Alt'], 'Comma', 700);
  ok((await cur()) === 'settings', 'Alt+, opens Settings');
  await closeApp();
  await page.evaluate(() => document.activeElement?.blur());
  await press('ArrowUp', 600);
  ok(await drawerOpen(), '↑ opens the Apps screen');
  await mod('./js/shell/drawer.js', 'closeDrawer');
  await sleep(300);
  await page.evaluate(() => document.activeElement?.blur());
  await press('ArrowDown', 500);
  ok(await qpOpen(), '↓ opens the Quick Panel');
