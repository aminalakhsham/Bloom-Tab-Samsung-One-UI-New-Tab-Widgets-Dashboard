  ok(!(await isLocked()), 'unlocked');
  await page.evaluate(() => import('./js/core/store.js').then((m) => m.setSetting('reduceMotion', true)));
  noErrors(mark, 'fading layers');

  // ════════════════════════════════════════ chevrons mirror once in Arabic; Do not disturb in the status bar
  mark = logs.length;
  await ctx.openApp('settings', { page: 'lock' });
  await sleep(700);
  const flips = await page.evaluate(() => import('./js/core/ui.js').then((m) => {
    // a row with a chevron, and the window's back button, in the open Settings page
    const box = document.querySelector('.app-win .app-page:last-child .app-body') || document.body;
    const r = m.row({ title: 'x', chevron: true, onClick() {} });
    box.prepend(r);
    const count = (svg, stop) => { let n = 0; for (let el = svg; el && el !== stop; el = el.parentElement) if (getComputedStyle(el).transform.startsWith('matrix(-1')) n++; return n; };
    const out = { chev: count(r.querySelector('.ou-row-chev svg'), r) };
    const back = document.querySelector('.app-win .app-back svg');
    if (back) out.back = count(back, document.querySelector('.app-win'));
    r.remove();
    return out;
  }));
  ok(flips.chev === (rtl ? 1 : 0) && (flips.back == null || flips.back === (rtl ? 1 : 0)), `row chevrons and the back arrow are flipped ${rtl ? 'once' : 'never'} (${JSON.stringify(flips)})`);
  await shot(P + 'shell-chevrons');
  await closeApp();
  ok(!(await exists('#statusbar .sb-dnd')), 'Do not disturb off: no icon in the status bar');
  await page.evaluate(() => import('./js/core/store.js').then((m) => m.setSetting('dnd', { ...m.setting('dnd'), on: true })));
  await sleep(400);
  ok(await exists('#statusbar .sb-dnd') && (await page.$eval('#statusbar .sb-dnd', (e) => e.title)) === (await S('sb.dnd')), 'Do not disturb on: its icon in the status bar');
