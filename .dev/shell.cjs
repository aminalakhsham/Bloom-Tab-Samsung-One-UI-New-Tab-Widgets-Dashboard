  await sleep(400);
  ok(!(await exists('#statusbar .sb-dnd')), 'and gone when it is turned off');
  const defs = await page.evaluate(() => import('./js/core/store.js').then((m) => ['mutedApps', 'dnd', 'textScale', 'highContrast', 'lockWallpaper', 'wallpaperDarkDim', 'appSizes', 'profileName', 'backupPictures', 'genDaily', 'wallSmooth', 'wallLiveBehindApps'].filter((k) => !(k in m.DEFAULT_SETTINGS))));
  ok(defs.length === 0, 'every Settings option has a default in DEFAULT_SETTINGS ' + defs);
  noErrors(mark, 'chevrons and status bar');
  ok(!(await exists('.app-error')), 'no app render errors');
