  ok(await page.evaluate((x, y) => !!document.elementFromPoint(x, y)?.closest('#drawer'), W / 2, H / 2), 'the open Apps screen takes clicks');
  ok(!(await hitAfterClose('./js/shell/drawer.js#closeDrawer', '#drawer', W / 2, H / 2)), 'a closing Apps screen no longer catches clicks');
