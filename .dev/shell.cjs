  noErrors(mark, 'keyboard');

  // ════════════════════════════════════════ closing layers don't catch clicks while they fade out
  mark = logs.length;
  await page.evaluate(() => import('./js/core/store.js').then((m) => m.setSetting('reduceMotion', false)));
  await sleep(400);
  // what a click at (x, y) would land on, 60 ms after the layer started to close (its fade takes ~400 ms)
  const hitAfterClose = (closeFn, sel, x, y) => page.evaluate(async (closeFn, sel, x, y) => {
    const [mod, fn] = closeFn.split('#');
    (await import(mod))[fn]();
    await new Promise((r) => setTimeout(r, 60));
    return !!document.elementFromPoint(x, y)?.closest(sel);
  }, closeFn, sel, x, y);
  await page.evaluate(() => import('./js/shell/drawer.js').then((m) => m.openDrawer()));
